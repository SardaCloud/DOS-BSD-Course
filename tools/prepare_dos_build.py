"""Prepare a buildable copy of the MS-DOS 4.00 source tree.

    python tools/prepare_dos_build.py [DEST]        (default: build/dos4)

Copies src-ext/MS-DOS/v4.0/src to DEST/SRC, converts text files from LF to CRLF
(the 1988 tools expect DOS line endings), and writes DEST/BUILD.BAT, which sets
the environment (a corrected SETENV.BAT: the repository keeps the compiler's
INCLUDE and LIB files under TOOLS\\BLD) and runs NMAKE. Mount DEST as drive D:
in DOSBox-X and run BUILD.BAT; see course/00-lab.md.
"""
from __future__ import annotations

import datetime as dt
import os
import re
import shutil
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src-ext" / "MS-DOS" / "v4.0" / "src"

BUILD_HEAD = r"""@echo off
rem Generated by tools/prepare_dos_build.py. Corrected SETENV.BAT for this tree
rem (drive D:, compiler files in TOOLS\BLD), then one NMAKE per directory in the
rem order of the original makefiles, with a marker line per directory in the log.
set CL=
set LINK=
set MASM=
set COUNTRY=usa-ms
set BAKROOT=D:
set LIB=D:\SRC\TOOLS\BLD\LIB
set INIT=D:\SRC\TOOLS
set INCLUDE=D:\SRC\TOOLS\BLD\INC
set PATH=D:\SRC\TOOLS;Z:\
if exist D:\BUILD.LOG del D:\BUILD.LOG
"""


def build_dirs(src: Path, rel: str = "") -> list[str]:
    """Directories to run NMAKE in, following the 'cd X / $(make)' aggregator makefiles."""
    mk = src / rel / "MAKEFILE" if rel else src / "MAKEFILE"
    lines = mk.read_text(encoding="latin-1").splitlines()
    m = next((i for i, ln in enumerate(lines) if re.match(r"^all\s*:", ln)), None)
    if m is None or lines[m].split(":", 1)[1].strip():
        return [rel]  # has its own targets: NMAKE handles any subdirectories itself
    out: list[str] = []
    cur = rel
    for ln in lines[m + 1:]:
        s = ln.strip()
        if not s:
            continue
        if not ln[:1].isspace():
            break
        if s.lower().startswith("cd "):
            for part in s[3:].strip().replace("/", "\\").split("\\"):
                if part == "..":
                    cur = cur.rsplit("\\", 1)[0] if "\\" in cur else ""
                elif part and part != ".":
                    cur = f"{cur}\\{part.upper()}" if cur else part.upper()
        elif "$(make)" in s.lower() or s.lower().startswith("nmake"):
            out += build_dirs(src, cur)
    return out


def build_bat(src: Path) -> str:
    lines = [BUILD_HEAD.rstrip("\n")]
    for d in build_dirs(src):
        lines += [f"echo ===== {d} >> D:\\BUILD.LOG", f"cd \\SRC\\{d}", "nmake >> D:\\BUILD.LOG"]
    lines += ["cd \\", "echo ===== done >> D:\\BUILD.LOG", ""]
    return "\n".join(lines)


def is_binary(p: Path, data: bytes) -> bool:
    # By content, not extension: ZERO.DAT and LOCSCR are text fed to EXE2BIN's stdin
    # and need CRLF, while INDEXMAE.SYS has no NUL bytes but is a binary.
    if b"\x00" in data:
        return True
    ctl = sum(1 for b in data if b < 0x20 and b not in (9, 10, 12, 13, 26))
    return ctl > len(data) // 100


def repair_utf8(data: bytes) -> tuple[bytes, bool]:
    """Undo damage from a UTF-8 conversion: some files in the repository had their
    CP437 bytes replaced by U+FFFD (3 bytes each), which makes long lines exceed
    MASM's limit. Map them back to one byte each ('?' where the original is lost)."""
    if not any(b >= 0x80 for b in data):
        return data, False
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return data, False  # genuine CP437 bytes: leave alone
    return text.encode("cp437", errors="replace"), True


def main() -> int:
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "dos4"
    if not SRC.is_dir():
        print("run tools/fetch_sources.ps1 first", file=sys.stderr)
        return 1
    if dest.exists():
        shutil.rmtree(dest, onexc=lambda fn, path, _: (os.chmod(path, stat.S_IWRITE), fn(path)))
    converted = copied = repaired = 0
    for p in SRC.rglob("*"):
        if p.is_dir():
            continue
        out = dest / "SRC" / p.relative_to(SRC)
        out.parent.mkdir(parents=True, exist_ok=True)
        data = p.read_bytes()
        if is_binary(p, data):
            out.write_bytes(data)
            copied += 1
        else:
            data, fixed = repair_utf8(data)
            repaired += fixed
            out.write_bytes(data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
            converted += 1
    (dest / "BUILD.BAT").write_bytes(build_bat(SRC).replace("\n", "\r\n").encode("ascii"))
    # DOSBox-X stamps new files with its own clock (UTC here), which can be behind the
    # host's local time. Give the sources a fixed past date so that NMAKE always sees
    # build outputs as newer; otherwise it re-runs NOSRVBLD, which then hangs.
    stamp = dt.datetime(2024, 4, 25, 12, 0).timestamp()
    for p in (dest / "SRC").rglob("*"):
        os.utime(p, (stamp, stamp))
    print(f"{dest}: {converted} text files converted to CRLF ({repaired} repaired from UTF-8), "
          f"{copied} binary files copied")
    return 0


if __name__ == "__main__":
    sys.exit(main())
